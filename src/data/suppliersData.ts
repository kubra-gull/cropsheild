export function generateWhatsAppUrl(supplier: Supplier, crop?: string, disease?: string): string {
  const cropText = crop || 'my crop';
  const diseaseText = disease || 'the detected crop issue';
  
  const message = `Hello, I used CropShield to identify a problem with my ${cropText} crop. The detected issue is ${diseaseText}. I would like information about suitable treatment products and guidance.`;
  
  return `https://wa.me/${supplier.whatsappNumber}?text=${encodeURIComponent(message)}`;
}
